-- Run once in Supabase > SQL Editor: video tutorials + KT documents library.
-- Everyone who is logged in can watch and download; only admins can add, replace or delete.
create table if not exists public.library (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('video','doc')),
  title text not null,
  descr text not null default '',
  cat text not null default 'General',
  link text not null default '',
  path text not null default '',
  fname text not null default '',
  ftype text not null default '',
  size bigint not null default 0,
  created_at timestamptz not null default now()
);
alter table public.library enable row level security;
create policy "library read"   on public.library for select to authenticated using (true);
create policy "library insert" on public.library for insert to authenticated with check (public.is_admin());
create policy "library update" on public.library for update to authenticated using (public.is_admin());
create policy "library delete" on public.library for delete to authenticated using (public.is_admin());

-- Private storage for the uploaded files (50 MB per file, the free-plan maximum)
insert into storage.buckets (id, name, public, file_size_limit)
values ('kt-library', 'kt-library', false, 52428800)
on conflict (id) do nothing;
create policy "kt-library read"   on storage.objects for select to authenticated using (bucket_id = 'kt-library');
create policy "kt-library insert" on storage.objects for insert to authenticated with check (bucket_id = 'kt-library' and public.is_admin());
create policy "kt-library update" on storage.objects for update to authenticated using (bucket_id = 'kt-library' and public.is_admin());
create policy "kt-library delete" on storage.objects for delete to authenticated using (bucket_id = 'kt-library' and public.is_admin());
