-- KT Academy · Supabase setup. Paste into Supabase Dashboard > SQL Editor > Run.

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  email text not null,
  role text not null default 'user' check (role in ('user','admin')),
  track text not null default 'Both' check (track in ('Both','Local','TestOps')),
  done bigint[] not null default '{}',
  certs jsonb not null default '{}'::jsonb,
  info jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.docs (
  id bigint generated by default as identity primary key,
  t text not null,
  c text not null check (c in ('Local','TestOps','Tools')),
  l text not null default 'Beginner',
  u text not null default '',
  b text not null default '',
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.docs enable row level security;

create or replace function public.is_admin() returns boolean
language sql security definer set search_path = public stable
as $$ select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin') $$;

-- Auto-create a profile whenever someone signs up
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public
as $$ begin
  insert into public.profiles (id, email, name, track)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'name',''), coalesce(new.raw_user_meta_data->>'track','Both'));
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

-- Only admins can change a role (blocks self-promotion)
create or replace function public.protect_role() returns trigger
language plpgsql security definer set search_path = public
as $$ begin
  if new.role <> old.role and auth.uid() is not null and not public.is_admin() then new.role := old.role; end if;
  return new;
end $$;
create trigger protect_role before update on public.profiles
for each row execute function public.protect_role();

-- profiles: users see/edit only themselves; admins see/edit/remove everyone
create policy "profiles read"   on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
create policy "profiles update" on public.profiles for update to authenticated using (id = auth.uid() or public.is_admin()) with check (id = auth.uid() or public.is_admin());
create policy "profiles delete" on public.profiles for delete to authenticated using (public.is_admin());

-- docs: any logged-in user can read; only admins can add/edit/delete
create policy "docs read"   on public.docs for select to authenticated using (true);
create policy "docs insert" on public.docs for insert to authenticated with check (public.is_admin());
create policy "docs update" on public.docs for update to authenticated using (public.is_admin());
create policy "docs delete" on public.docs for delete to authenticated using (public.is_admin());

